#!/usr/bin/env node
// Regenerate src/supply-chain/popular-names.ts: the most downloaded names of
// npm and PyPI, which the lookalike check compares install names against
// (node9Firewall#385, wave 3). Run before a release; commit the result.
//
//   node scripts/update-popular-names.mjs [--count 5000]
//
// Sources (THIRD_PARTY_NOTICES.md):
//   npm:  npm-high-impact (MIT), `topDownload`: names with a million or more
//         downloads a week, ordered by downloads.
//   PyPI: top-pypi-packages (Hugo van Kemenade), the 15,000 most downloaded
//         projects over the last 30 days, from PyPI's public download data.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const COUNT = Number(process.argv[process.argv.indexOf('--count') + 1]) || 5000;
const NPM_URL = 'https://unpkg.com/npm-high-impact/lib/top-download.js';
const NPM_PKG_URL = 'https://registry.npmjs.org/npm-high-impact/latest';
const PYPI_URL = 'https://hugovk.dev/top-pypi-packages/top-pypi-packages.min.json';
const OUT = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'supply-chain',
  'popular-names.ts'
);

async function text(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

/** PEP 503: lowercase, runs of `-`, `_` and `.` become one `-`. */
const normalizePyPi = (name) => name.toLowerCase().replace(/[-_.]+/g, '-');

const npmSource = await text(NPM_URL);
const npmVersion = JSON.parse(await text(NPM_PKG_URL)).version;
const npm = [...npmSource.matchAll(/'([^']+)'/g)].map((m) => m[1].toLowerCase());
if (npm.length < COUNT) throw new Error(`npm list has ${npm.length} names, wanted ${COUNT}`);
const pypi = JSON.parse(await text(PYPI_URL));
if (pypi.rows.length < COUNT) throw new Error(`PyPI list has ${pypi.rows.length} rows`);

const unique = (names) => [...new Set(names)].slice(0, COUNT);
const npmNames = unique(npm);
const pypiNames = unique(pypi.rows.map((r) => normalizePyPi(r.project)));
const lines = (names) => names.map((n) => `  ${JSON.stringify(n)},`).join('\n');

fs.writeFileSync(
  OUT,
  `// Generated by scripts/update-popular-names.mjs on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand. The ${COUNT} most downloaded names of each registry,
// lowercase, PyPI names normalized (PEP 503). Compared against install names
// by the lookalike check (lookalike.ts). Sources in THIRD_PARTY_NOTICES.md:
// npm from npm-high-impact ${npmVersion} (topDownload), PyPI from
// top-pypi-packages updated ${String(pypi.last_update).slice(0, 10)}.

export const POPULAR_NPM: readonly string[] = [
${lines(npmNames)}
];

export const POPULAR_PYPI: readonly string[] = [
${lines(pypiNames)}
];
`
);
console.log(`wrote ${OUT}: npm ${npmNames.length}, PyPI ${pypiNames.length}`);
