/**
 * Generates the JavaScript plugin file dropped into
 * `~/.config/opencode/plugins/node9.js` by setupOpencode.
 *
 * Why this lives in its own file:
 *   - Keeps setup.ts from carrying ~150 lines of embedded JS source text.
 *   - Makes the shim contract testable in isolation.
 *
 * OpenCode ships two plugin APIs, and both are in use at the same time
 * (npm `latest` is 1.x while 2.x is released on GitHub). One file serves
 * both, because both loaders read the module's DEFAULT export:
 *
 *   • OpenCode 1.x (readV1Plugin, packages/opencode/src/plugin/shared.ts)
 *     needs `default = { id, server() }`. server() returns a hooks object:
 *       tool.execute.before — pre-execution block (throws on deny verdict)
 *       tool.execute.after  — audit + output redaction (mutates out.output)
 *       chat.message        — prompt DLP (paste-into-prompt secret scan)
 *
 *   • OpenCode 2.x (PluginModule, packages/core/src/plugin/module.ts)
 *     needs `default = { id, setup() }` and REJECTS a module without it
 *     (issue #480: the v1-only shim never loaded, so OpenCode 2 ran with
 *     no node9 checks at all). setup(host) registers:
 *       host.tool.hook("execute.before") — a throw becomes a Tool.Error and
 *                                          rejects that call
 *       host.tool.hook("execute.after")  — reassigning ev.result changes
 *                                          what the model sees
 *       host.session.hook("prompt")      — a throw stops the prompt
 *
 * Each loader ignores the other's key (v1 reads only server/tui, v2's
 * schema ignores extra properties), so the file carries both.
 *
 * The shim runs the node9 CLI via an embedded NODE9_ARGV array, with an
 * async spawn: OpenCode runs plugins inside its server process, and a
 * spawnSync would freeze that event loop for the whole of an approval
 * wait. setupOpencode resolves the argv at install time so a stripped
 * $PATH at OpenCode launch doesn't break interception.
 */

/**
 * Marker for the plugin shape this file carries. doctor reads it: a shim
 * without it predates OpenCode 2 support and is refused by OpenCode 2.x.
 * Bump only when the shape changes, never per release.
 */
export const OPENCODE_SHIM_SHAPE = 'v1+v2';
const SHAPE_LINE = `// NODE9_SHIM_SHAPE = "${OPENCODE_SHIM_SHAPE}"`;

/** True when the shim text on disk carries the current plugin shape. */
export function opencodeShimHasCurrentShape(shimText: string): boolean {
  return shimText.includes(SHAPE_LINE);
}

export interface OpencodeShimInput {
  /**
   * The argv prefix used to invoke node9. Two production shapes:
   *
   *   • Global npm install — `["/usr/local/bin/node9"]` (the bin script
   *     created by npm, has a shebang and the executable bit set).
   *
   *   • Dev / npm-link — `["/path/to/node", "/path/to/dist/cli.js"]`
   *     (node executes the cli.js directly).
   *
   * Resolved by setupOpencode via process.argv[1] / process.execPath at
   * `node9 init` time. The shim then invokes
   * `spawn(argv[0], [...argv.slice(1), "check"], ...)` which works
   * cross-platform without going through a shell.
   */
  node9Argv: string[];
  /**
   * Current node9 version. Embedded as a constant so subsequent inits
   * can detect mismatched shims and self-heal.
   */
  version: string;
}

export function renderOpencodeShim(input: OpencodeShimInput): string {
  const { node9Argv, version } = input;
  // Plain CommonJS. Both OpenCode loaders import() the file, and an
  // imported CommonJS module's default export is module.exports. We avoid
  // `import` statements because user-dropped plugin files have no
  // node_modules resolution context.
  return `// Auto-generated by \`node9 init\`. Do not edit — re-run init to upgrade.
// NODE9_SHIM_VERSION = "${version}"
${SHAPE_LINE}
//
// node9 protection shim for OpenCode 1.x and 2.x. Wires the pre-tool,
// post-tool and prompt hooks of whichever plugin API loads it, and asks
// the node9 CLI for a verdict. Blocking is done by throwing from a hook.

const { spawn } = require("node:child_process");

// argv prefix for invoking the node9 CLI. argv[0] is the executable
// (either the npm-installed wrapper script or the node binary); the
// remaining entries (if any) are passed as the leading args before
// the subcommand name (e.g. ["/path/to/dist/cli.js"] for dev mode).
const NODE9_ARGV = ${JSON.stringify(node9Argv)};
const HOOK_TIMEOUT_MS = 30000;
const LOG_TIMEOUT_MS = 5000;
const AGENT = "Opencode";

// Run the node9 CLI with a JSON payload on stdin. Resolves to
// { status, stdout }; status is null when the CLI could not be started
// or ran past the timeout. Never rejects.
function runNode9(args, payload, timeoutMs) {
  return new Promise((resolve) => {
    let stdout = "";
    let settled = false;
    let timer = null;
    const finish = (status) => {
      if (settled) return;
      settled = true;
      if (timer) clearTimeout(timer);
      resolve({ status, stdout });
    };
    let child;
    let body;
    try {
      // Serialise before spawning: a value JSON cannot encode must not leave a
      // started node9 waiting on stdin until the timeout.
      body = JSON.stringify(payload);
      child = spawn(NODE9_ARGV[0], [...NODE9_ARGV.slice(1), ...args], {
        stdio: ["pipe", "pipe", "ignore"],
      });
    } catch (e) {
      finish(null);
      return;
    }
    timer = setTimeout(() => {
      try {
        child.kill("SIGKILL");
      } catch (e) {
        // already gone
      }
      finish(null);
    }, timeoutMs);
    child.on("error", () => finish(null));
    child.on("close", (code) => finish(code));
    child.stdout.setEncoding("utf-8");
    child.stdout.on("data", (chunk) => {
      stdout += chunk;
    });
    child.stdin.on("error", () => {});
    child.stdin.end(body);
  });
}

function parseReason(stdout) {
  // node9 check emits {decision, reason, message} JSON on stdout when
  // blocking. Fall back to a generic string if anything goes wrong.
  try {
    const v = JSON.parse(stdout || "");
    return v && (v.reason || v.message);
  } catch (e) {
    return null;
  }
}

// Fail closed: anything but a clean exit 0 (a deny, a crash, a timeout,
// a missing binary) blocks.
async function checkOrThrow(payload, fallback) {
  const r = await runNode9(["check"], payload, HOOK_TIMEOUT_MS);
  if (r.status === 0) return;
  throw new Error("[node9] " + (parseReason(r.stdout) || fallback));
}

function preToolUse(tool, args, sessionID, cwd) {
  return checkOrThrow(
    {
      hook_event_name: "PreToolUse",
      tool_name: tool,
      tool_input: args,
      session_id: sessionID,
      cwd,
      meta: { agent: AGENT },
    },
    "blocked by node9"
  );
}

function promptCheck(prompt, sessionID) {
  if (!prompt) return Promise.resolve();
  return checkOrThrow(
    {
      hook_event_name: "UserPromptSubmit",
      prompt,
      session_id: sessionID,
      meta: { agent: AGENT },
    },
    "prompt blocked"
  );
}

// Audit + response-channel DLP: send the tool OUTPUT to node9 log and
// return the redacted text when the model must not see the original
// (a secret was found, or the text was framed as injected), else null.
// Never throws: the tool already ran.
async function postToolUse(tool, args, sessionID, cwd, output) {
  try {
    const r = await runNode9(
      ["log", "--redact-output"],
      {
        hook_event_name: "PostToolUse",
        tool_name: tool,
        tool_input: args,
        session_id: sessionID,
        cwd,
        tool_response: { output },
        meta: { agent: AGENT },
      },
      LOG_TIMEOUT_MS
    );
    if (r.status !== 0 || !r.stdout) return null;
    const resp = JSON.parse(r.stdout);
    // A frame alone has found=[], so injection counts on its own.
    if (
      resp &&
      typeof resp.redacted === "string" &&
      ((Array.isArray(resp.found) && resp.found.length > 0) || resp.injection)
    ) {
      return resp.redacted;
    }
  } catch (e) {
    // Swallow: a redaction/audit failure must not crash the agent.
  }
  return null;
}

// ── OpenCode 1.x ──────────────────────────────────────────────────────────

function extractPromptText(parts) {
  // chat.message gives us parts: Part[]. We only DLP-scan text parts
  // (image / tool_use parts can't contain pasted secrets in any form
  // node9's scanner currently recognizes).
  if (!Array.isArray(parts)) return "";
  return parts
    .filter((p) => p && p.type === "text")
    .map((p) => (p && p.text) || "")
    .join("\\n");
}

async function server(input) {
  const cwd = input && input.directory;
  return {
    "tool.execute.before": async (ctx, mutable) => {
      await preToolUse(ctx.tool, mutable.args, ctx.sessionID, cwd);
    },

    "tool.execute.after": async (ctx, out) => {
      // The host returns this same \`out\` object after the hook, so
      // mutating out.output replaces what the model sees.
      const toolOutput = out && typeof out.output === "string" ? out.output : "";
      const redacted = await postToolUse(ctx.tool, ctx.args, ctx.sessionID, cwd, toolOutput);
      if (redacted !== null && out && typeof out.output === "string") out.output = redacted;
    },

    "chat.message": async (ctx, mutable) => {
      await promptCheck(extractPromptText(mutable.parts), ctx.sessionID);
    },
  };
}

// ── OpenCode 2.x ──────────────────────────────────────────────────────────

// The text the model will read from a tool result: content when present
// (a string or text parts), else the stringified structured output
// (the same order the host's normalizeContent uses).
function resultText(result) {
  const content = result.content;
  if (typeof content === "string") return content;
  if (Array.isArray(content) && content.length > 0) {
    return content
      .filter((c) => c && c.type === "text" && typeof c.text === "string")
      .map((c) => c.text)
      .join("\\n");
  }
  if (typeof result.output === "string") return result.output;
  try {
    return JSON.stringify(result.output) || "";
  } catch (e) {
    return "";
  }
}

// Replace every text channel of a result with the redacted text. File
// parts (images) are kept; they were not scanned and carry no text.
function redactResult(result, redacted) {
  const next = { ...result, content: redacted };
  if (Array.isArray(result.content)) {
    const files = result.content.filter((c) => c && c.type !== "text");
    next.content = [{ type: "text", text: redacted }, ...files];
  }
  if (typeof result.output === "string") {
    next.output = redacted;
  } else if (result.output && typeof result.output === "object" && typeof result.output.output === "string") {
    // The shell tool's structured output repeats the text in .output.
    next.output = { ...result.output, output: redacted };
  }
  return next;
}

async function setup(host) {
  const cwd =
    host && host.location && typeof host.location.directory === "string"
      ? host.location.directory
      : process.cwd();

  await host.tool.hook("execute.before", async (ev) => {
    await preToolUse(ev.tool, ev.input, ev.sessionID, cwd);
  });

  await host.tool.hook("execute.after", async (ev) => {
    try {
      const result = ev.status === "completed" && ev.result ? ev.result : null;
      const redacted = await postToolUse(ev.tool, ev.input, ev.sessionID, cwd, result ? resultText(result) : "");
      if (redacted !== null && result) ev.result = redactResult(result, redacted);
    } catch (e) {
      // Must never throw: the tool already ran.
    }
  });

  await host.session.hook("prompt", async (ev) => {
    const text = ev && ev.prompt && typeof ev.prompt.text === "string" ? ev.prompt.text : "";
    await promptCheck(text, ev && ev.sessionID);
  });
}

module.exports = { id: "node9", server, setup };
`;
}
